-- =============================================================================
-- Migration 017 — integrated product, storefront, test-order and sync quality.
--
-- 1) Generate a unique SKU when a merchant leaves the optional SKU blank.
-- 2) Add an auditable, one-way academic-test marker to orders. Test orders are
--    excluded from merchant/admin sales, GMV, customer and popularity analytics;
--    payment transactions and audit logs remain immutable.
-- 3) Return the selected theme accent in the public storefront projection.
-- 4) Add store-scoped catalog/stock tables to Supabase Realtime publication.
