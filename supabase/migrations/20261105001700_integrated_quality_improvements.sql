-- -----------------------------------------------------------------------------
-- 1. Optional SKU input, guaranteed unique persisted SKU.
-- -----------------------------------------------------------------------------
create or replace function private.assign_product_sku()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if nullif(trim(new.sku), '') is null then
    new.sku := 'BHQ-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));
  else
    new.sku := trim(new.sku);
  end if;
  return new;
end;
$$;

create trigger products_assign_sku
before insert or update on public.products
for each row execute function private.assign_product_sku();

-- Backfill legacy rows that were created before the auto-SKU trigger existed.
update public.products
set sku = 'BHQ-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10))
where nullif(trim(sku), '') is null;

comment on column public.products.sku is
  'Optional merchant input. When blank, a unique BHQ-* SKU is generated by products_assign_sku.';

-- -----------------------------------------------------------------------------
-- 2. Auditable academic/test order marker (never deletes payment/audit history).
-- -----------------------------------------------------------------------------
alter table public.orders
  add column if not exists is_test boolean not null default false,
  add column if not exists test_reason text,
  add column if not exists test_marked_at timestamptz,
  add column if not exists test_marked_by uuid references public.profiles(id) on delete restrict;

alter table public.orders
  add constraint orders_test_marker_consistency_check
  check (
    (is_test = false and test_reason is null and test_marked_at is null and test_marked_by is null)
    or
    (is_test = true and test_reason is not null and test_marked_at is not null and test_marked_by is not null)
  );

create index if not exists orders_store_test_created_idx
  on public.orders (store_id, is_test, created_at desc);

comment on column public.orders.is_test is
  'Internal academic/test marker. Test orders remain in the immutable transaction history but are excluded from business analytics.';
comment on column public.orders.test_reason is
  'Merchant-provided reason for marking an order as an academic/test record.';

create or replace function public.mark_order_as_test(p_order_id uuid, p_reason text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_actor uuid := (select auth.uid());
  v_store public.stores%rowtype;
  v_order public.orders%rowtype;
  v_reason text := nullif(trim(coalesce(p_reason, '')), '');
begin
  v_store := private.require_merchant_store(v_actor);

  if v_reason is null or length(v_reason) not between 5 and 300 then
    raise exception 'Add a reason between 5 and 300 characters' using errcode = '22023';
  end if;

  select * into v_order
  from public.orders
  where id = p_order_id and store_id = v_store.id
  for update;

  if not found then
    raise exception 'Order not found' using errcode = 'P0002';
  end if;

  -- Idempotent: the first test marker and reason remain the authoritative audit note.
  if v_order.is_test then
    return v_order.id;
  end if;

  update public.orders
  set is_test = true,
      test_reason = v_reason,
      test_marked_at = now(),
      test_marked_by = v_actor
  where id = v_order.id;

  perform private.audit(
    v_actor,
    'order.marked_test',
    'order',
    v_order.id,
    jsonb_build_object(
      'order_number', v_order.order_number,
      'reason', v_reason,
      'payment_status_unchanged', true,
      'payment_transactions_unchanged', true
    )
  );

  return v_order.id;
end;
$$;

revoke all on function public.mark_order_as_test(uuid, text) from public, anon;
grant execute on function public.mark_order_as_test(uuid, text) to authenticated;
comment on function public.mark_order_as_test(uuid, text) is
  'One-way merchant-owned academic test marker. Does not change order/payment state or delete payment/audit records.';

