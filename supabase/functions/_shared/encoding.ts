/**
 * Small, dependency-free encoders and MD5.
 *
 * MD5 is required only by SSLCommerz' documented IPN signature scheme
 * (verify_sign); it is not used for any of our own security decisions. WebCrypto
 * has no MD5, so this is the RFC 1321 algorithm, checked against the RFC test
 * vectors in encoding.test.ts.
 */

export function encodeHex(bytes: Uint8Array | ArrayBuffer): string {
  const b = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  let out = '';
  for (const x of b) out += x.toString(16).padStart(2, '0');
  return out;
}

export function encodeBase64Url(bytes: Uint8Array | ArrayBuffer): string {
  const b = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  let bin = '';
  for (const x of b) bin += String.fromCharCode(x);
  return btoa(bin).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
}

export function decodeBase64UrlToString(input: string): string {
  const b64 = input.replace(/-/g, '+').replace(/_/g, '/');
  const bin = atob(b64.padEnd(b64.length + ((4 - (b64.length % 4)) % 4), '='));
  const bytes = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
  return new TextDecoder().decode(bytes);
}

