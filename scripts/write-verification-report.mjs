#!/usr/bin/env node
/**
 * Turns the JSON written by the verification scripts (REPORT_DIR=verification)
 * into docs/reports/ROUTE_VERIFICATION.md.
 *   REPORT_DIR=verification npm run verify:routes   (and verify:mobile, e2e:web)
 *   npm run report:verification
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const DIR = process.env.REPORT_DIR ?? 'verification';
const read = (name) => (existsSync(`${DIR}/${name}.json`) ? JSON.parse(readFileSync(`${DIR}/${name}.json`, 'utf8')) : null);
const web = read('web-routes');
const mobile = read('mobile-routes');
const e2e = read('e2e-web');
const commands = read('commands');

const esc = (v) => String(v ?? '—').replace(/\|/g, '\\|');
const lines = [
  '# Route verification report',
  '',
  'Generated by `scripts/write-verification-report.mjs` from the JSON written by the Playwright verification scripts.',
  '',
];

if (commands) {
  lines.push('## Commands', '', `Run on ${commands.at}.`, '', '| Command | Result | Notes |', '|---|---|---|');
  for (const c of commands.items) lines.push(`| \`${c.command}\` | ${c.ok === null ? 'Not run' : c.ok ? 'Pass' : '**Fail**'} | ${esc(c.notes)} |`);
  lines.push('');
}

function section(title, data, cols) {
  if (!data) return lines.push(`## ${title}`, '', '_Not run._', '');
  const failed = (data.failures ?? data.errors ?? []).length;
  lines.push(
    `## ${title}`,
    '',
    `${data.results.length} checks against \`${data.base}\` on ${data.at} — **${failed ? `${failed} failed` : 'all passed'}**.`,
    '',
  );
  lines.push(`| ${cols.map((c) => c[0]).join(' | ')} |`, `|${cols.map(() => '---').join('|')}|`);
  for (const r of data.results) lines.push(`| ${cols.map((c) => esc(c[1](r))).join(' | ')} |`);
  lines.push('');
  if (failed) lines.push('```json', JSON.stringify(data.failures ?? data.errors, null, 2), '```', '');
}

section('Web routes (Customer, Merchant, Super Admin)', web, [
  ['Route', (r) => r.route],
  ['Viewport', (r) => r.viewport],
  ['Status', (r) => r.status],
  ['H1', (r) => r.h1],
  ['Overflow px', (r) => r.overflow],
  ['Errors', (r) => r.errors],
]);
section('Android SPA routes and role navigation', mobile, [
  ['Route / check', (r) => r.route],
  ['H1 / tabs', (r) => r.h1],
  ['Overflow px', (r) => r.overflow],
  ['Errors', (r) => r.errors],
]);
section('Web end-to-end flows', e2e, [
  ['Flow', (r) => r.step],
  ['Result', (r) => (r.ok === '✓' ? 'Pass' : 'Fail')],
]);

writeFileSync('docs/reports/ROUTE_VERIFICATION.md', lines.join('\n'));
console.log('Wrote docs/reports/ROUTE_VERIFICATION.md');
